def search_seeds(keyword: str, count: int = 50) -> list[str]:
    """根据关键词匹配种子名单中的企业名。"""
    kw = keyword.strip()
    results = []
    # 精确匹配行业分类
    for industry, name in SEEDS:
        if kw in industry or industry in kw:
            results.append(name)
    # 模糊匹配企业名
    for industry, name in SEEDS:
        if kw in name and name not in results:
            results.append(name)
    # 如果没匹配到，返回全部（去重）
    if not results:
        seen = set()
        for _, name in SEEDS:
            if name not in seen:
                results.append(name)
                seen.add(name)
    return results[:count]
